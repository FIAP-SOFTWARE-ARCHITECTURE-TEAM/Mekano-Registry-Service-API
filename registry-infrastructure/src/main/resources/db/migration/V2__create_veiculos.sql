-- V2__create_veiculos.sql
-- Tabela de veiculos do Registry, com referencia logica ao cliente por UUID.

CREATE TABLE veiculos
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid        UUID         NOT NULL,
    cliente_uuid UUID        NOT NULL,
    placa       VARCHAR(8)   NOT NULL,
    marca       VARCHAR(100),
    modelo      VARCHAR(100),
    ano         INTEGER,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP,
    created_by  VARCHAR(100),
    updated_by  VARCHAR(100),
    deleted_at  TIMESTAMP,
    CONSTRAINT pk_veiculos PRIMARY KEY (id),
    CONSTRAINT ux_veiculos_uuid UNIQUE (uuid),
    CONSTRAINT fk_veiculos_cliente_uuid FOREIGN KEY (cliente_uuid) REFERENCES clientes (uuid)
);

CREATE UNIQUE INDEX ux_veiculos_placa_active
    ON veiculos (placa)
    WHERE is_active = TRUE AND deleted_at IS NULL;

CREATE INDEX ix_veiculos_cliente_uuid ON veiculos (cliente_uuid);
CREATE INDEX ix_veiculos_placa ON veiculos (placa);
