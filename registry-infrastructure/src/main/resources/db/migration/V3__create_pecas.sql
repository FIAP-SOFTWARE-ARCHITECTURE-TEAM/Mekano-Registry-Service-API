CREATE TABLE pecas
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid           UUID          NOT NULL,
    codigo         VARCHAR(50)   NOT NULL,
    descricao      VARCHAR(255)  NOT NULL,
    valor_unitario NUMERIC(12,2) NOT NULL,
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP     NOT NULL,
    updated_at     TIMESTAMP,
    created_by     VARCHAR(100),
    updated_by     VARCHAR(100),
    deleted_at     TIMESTAMP,
    CONSTRAINT pk_pecas PRIMARY KEY (id),
    CONSTRAINT ux_pecas_uuid UNIQUE (uuid),
    CONSTRAINT ck_pecas_valor_unitario_positive CHECK (valor_unitario > 0)
);

CREATE UNIQUE INDEX ux_pecas_codigo_active
    ON pecas (codigo)
    WHERE is_active = TRUE AND deleted_at IS NULL;

CREATE INDEX ix_pecas_descricao ON pecas (descricao);
